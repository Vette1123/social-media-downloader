/**
 * Promotes prerendered binary routes into real Workers static assets.
 *
 * Runs after `opennextjs-cloudflare build`, as part of `pnpm cf:build`.
 *
 * The 24 OpenGraph/Twitter card images are prerendered at build time, but by
 * default they are only reachable through the incremental cache, which means
 * the Worker has to run to serve them. Cloudflare matches static assets *before*
 * invoking the Worker, so copying the finished PNG bytes to the asset directory
 * at their public paths means those requests cost zero CPU and are not billed
 * as Worker invocations at all.
 *
 * That matters twice over: satori rasterization is what blew the 10 ms CPU
 * budget in the first place (every image route returned `error code 1102` in
 * production), and these are the largest responses the site serves.
 *
 * The bytes come from OpenNext's own cache entries rather than being
 * re-rendered, so what ships is exactly what the build produced. The entries
 * are left in place as well: if this script ever fails to match a route, the
 * Worker still serves it the slow way instead of 404ing.
 *
 * Because the public paths have no file extension (`/opengraph-image`), a
 * `_headers` file supplies the Content-Type that would otherwise be guessed.
 */

import { readFileSync, writeFileSync, mkdirSync, readdirSync, existsSync, statSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const CACHE_DIR = path.join(ROOT, '.open-next', 'cache')
const ASSETS_DIR = path.join(ROOT, '.open-next', 'assets')
const HEADERS_FILE = path.join(ASSETS_DIR, '_headers')

// Long enough to be worth caching, short enough that redesigned cards actually
// propagate to crawlers. Next's own default here was `max-age=0`.
const IMAGE_CACHE_CONTROL = 'public, max-age=86400, stale-while-revalidate=604800'

// A guard against silently shipping nothing if OpenNext changes its cache
// layout: 12 pages (home + 11 platforms) x 2 social cards, plus the 4
// prerendered PWA icons (/icons/192, /512, /apple, /maskable).
const EXPECTED_IMAGE_COUNT = 28

const MARKER_START = '# --- generated by scripts/cf-static-assets.mjs ---'
const MARKER_END = '# --- end generated ---'

function fail(message) {
  console.error(`\x1b[31m✗\x1b[0m cf-static-assets: ${message}`)
  process.exit(1)
}

/** Every *.cache file under a directory, returned as absolute paths. */
function findCacheFiles(dir) {
  const found = []
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) found.push(...findCacheFiles(full))
    else if (entry.name.endsWith('.cache')) found.push(full)
  }
  return found
}

/**
 * The build-id directory holding this build's entries. `__fetch` sits alongside
 * it and holds fetch-cache data, which is not route output.
 */
function resolveBuildDir() {
  if (!existsSync(CACHE_DIR)) {
    fail(`no cache directory at ${path.relative(ROOT, CACHE_DIR)} — run \`pnpm cf:build\` first`)
  }
  const candidates = readdirSync(CACHE_DIR, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && entry.name !== '__fetch')
    .map((entry) => path.join(CACHE_DIR, entry.name))

  if (candidates.length !== 1) {
    fail(`expected exactly one build-id directory in the cache, found ${candidates.length}`)
  }
  return candidates[0]
}

function main() {
  const buildDir = resolveBuildDir()
  const cacheFiles = findCacheFiles(buildDir)
  if (cacheFiles.length === 0) fail('no .cache entries found — did the build succeed?')

  const promoted = []

  for (const file of cacheFiles) {
    let entry
    try {
      entry = JSON.parse(readFileSync(file, 'utf8'))
    } catch {
      // Not every cache entry is JSON in every OpenNext version; skipping is
      // safe because the Worker fallback still serves the route.
      continue
    }

    const contentType = entry?.meta?.headers?.['content-type']
    // Only binary route output. HTML pages are deliberately left alone: Next
    // serves them through the cache so that client-side navigation, which asks
    // for an RSC payload at the same path, keeps working. A static asset would
    // shadow that and break soft navigation.
    if (entry?.type !== 'route' || typeof contentType !== 'string') continue
    if (!contentType.startsWith('image/')) continue
    if (typeof entry.body !== 'string') continue
    if (entry?.meta?.status && entry.meta.status !== 200) continue

    // .open-next/cache/<buildId>/tiktok-downloader/opengraph-image.cache
    //   -> /tiktok-downloader/opengraph-image
    const relative = path.relative(buildDir, file).replace(/\.cache$/, '')
    const routePath = '/' + relative.split(path.sep).join('/')

    const bytes = Buffer.from(entry.body, 'base64')
    if (bytes.length === 0) fail(`decoded an empty body for ${routePath}`)

    const target = path.join(ASSETS_DIR, relative)
    mkdirSync(path.dirname(target), { recursive: true })
    writeFileSync(target, bytes)

    promoted.push({ routePath, contentType, bytes: bytes.length })
  }

  if (promoted.length === 0) {
    fail('found no prerendered image routes to promote — the cache format may have changed')
  }
  if (promoted.length !== EXPECTED_IMAGE_COUNT) {
    // Not fatal: adding a platform legitimately changes the count. Loud, so it
    // is never mistaken for full coverage.
    console.warn(
      `\x1b[33m!\x1b[0m cf-static-assets: promoted ${promoted.length} images, expected ${EXPECTED_IMAGE_COUNT}. ` +
        'Update EXPECTED_IMAGE_COUNT if a platform was added or removed.',
    )
  }

  writeHeaders(promoted)

  const totalKiB = Math.round(promoted.reduce((sum, p) => sum + p.bytes, 0) / 1024)
  console.log(
    `\x1b[32m✓\x1b[0m cf-static-assets: promoted ${promoted.length} prerendered images ` +
      `(${totalKiB} KiB) to static assets — these now bypass the Worker entirely`,
  )
}

/**
 * Writes the Content-Type rules, preserving any hand-written content already in
 * `_headers` by replacing only the block between the markers.
 */
function writeHeaders(promoted) {
  const block = [
    MARKER_START,
    '# Extension-less asset paths need an explicit Content-Type, and these are',
    '# served straight from Workers Assets without the Worker running.',
    ...promoted.flatMap(({ routePath, contentType }) => [
      routePath,
      `  Content-Type: ${contentType}`,
      `  Cache-Control: ${IMAGE_CACHE_CONTROL}`,
    ]),
    MARKER_END,
  ].join('\n')

  let existing = ''
  if (existsSync(HEADERS_FILE) && statSync(HEADERS_FILE).isFile()) {
    existing = readFileSync(HEADERS_FILE, 'utf8')
  }

  const startIndex = existing.indexOf(MARKER_START)
  const endIndex = existing.indexOf(MARKER_END)
  const hasBlock = startIndex !== -1 && endIndex > startIndex

  const next = hasBlock
    ? existing.slice(0, startIndex) + block + existing.slice(endIndex + MARKER_END.length)
    : (existing ? existing.replace(/\s*$/, '\n\n') : '') + block + '\n'

  mkdirSync(ASSETS_DIR, { recursive: true })
  writeFileSync(HEADERS_FILE, next)
}

main()
